# Fig 4: triage scatter
def true_err(ext, d):
    return len(gold_error_records(ext, d)["errors"])

M2 = "deepseek-ai/DeepSeek-V3"; bs, es = [], []
for i in range(len(DOCS)):
    p = os.path.join(ROOT, "result", "extractions", safe(M2), f"{i:04d}.json")
    if not os.path.exists(p):
        continue
    ext = json.load(open(p))
    if ext.get("_error"):
        continue
    vs, et = find_violations(ext, SIGS, "empirical"); vs, _ = validate_against_gold(vs, et, DOCS[i])
    bs.append(disjoint_lower_bound([v["he"] for v in vs])); es.append(true_err(ext, DOCS[i]))
rx = np.argsort(np.argsort(bs)); ry = np.argsort(np.argsort(es)); rho = np.corrcoef(rx, ry)[0, 1]
fig, ax = plt.subplots(figsize=(5.4, 3.6))
jit = lambda a: np.array(a) + np.random.RandomState(0).uniform(-0.15, 0.15, len(a))
ax.scatter(jit(bs), es, s=18, alpha=0.5, color="#4C72B0")
ax.set_xlabel("Certificate lower bound (per document)"); ax.set_ylabel("True error count (vs gold)")
ax.set_title(f"Certificate bound vs. true errors — DeepSeek-V3 (Spearman rho={rho:.2f})")
plt.savefig(os.path.join(FIG, "fig4_triage.pdf")); plt.savefig(os.path.join(FIG, "fig4_triage.png")); plt.close()
print("fig4 ok rho", round(rho,3))
