FIG = os.path.join(ROOT, "result", "figs")
os.makedirs(FIG, exist_ok=True)
DOCS = json.load(open(os.path.join(ROOT, "data", "redocred_dev_300.json")))
SIGS = json.load(open(os.path.join(ROOT, "data", "relations.json")))
MODELS = ["Qwen/Qwen2.5-7B-Instruct", "Qwen/Qwen2.5-14B-Instruct", "Qwen/Qwen2.5-32B-Instruct",
          "Qwen/Qwen2.5-72B-Instruct", "deepseek-ai/DeepSeek-V3"]
LABELS = ["Qwen2.5\n7B", "Qwen2.5\n14B", "Qwen2.5\n32B", "Qwen2.5\n72B", "DeepSeek\nV3"]
safe = lambda m: m.replace("/", "__")


def per_model():
    rows = []
    for m in MODELS:
        valid = fired = ndoc = viol = sound = 0
        for i in range(len(DOCS)):
            p = os.path.join(ROOT, "result", "extractions", safe(m), f"{i:04d}.json")
            if not os.path.exists(p):
                continue
            ndoc += 1
            try:
                ext = json.load(open(p))
            except Exception:
                continue
            ents = [e for e in ext.get("entities", []) if isinstance(e, dict) and e.get("type") in TYPES]
            if not ents and not ext.get("relations"):
                continue
            valid += 1
            vs, et = find_violations(ext, SIGS, "empirical")
            vs, _ = validate_against_gold(vs, et, DOCS[i])
            b = disjoint_lower_bound([v["he"] for v in vs])
            fired += (b > 0)
            chk = [v for v in vs if v["checkable"]]
            viol += len(chk); sound += sum(1 for v in chk if v["sound"])
        rows.append(dict(valid=valid / ndoc, fired=fired / max(valid, 1),
                         sound=(sound / viol if viol else 1.0)))
    return rows


# Fig 2: model gradient
